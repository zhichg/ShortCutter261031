"""Generate the offline character map and non-default phrase readings."""
from pathlib import Path
import unicodedata

ROOT = Path(__file__).resolve().parent.parent


def plain(text):
    text = text.translate(str.maketrans({c: 'v' for c in 'üǖǘǚǜ'}))
    return ''.join(c for c in unicodedata.normalize('NFD', text)
                   if not unicodedata.combining(c))


def wide(text):
    # Use UTF-16 escapes so binary-search order matches Windows wchar_t order.
    units = text.encode('utf-16-le')
    return 'L"' + ''.join('\\x%04x' % int.from_bytes(units[i:i+2], 'little')
                          for i in range(0, len(units), 2)) + '"'


characters = {}
for line in (ROOT / 'third_party/pinyin-data/pinyin.txt').read_text(encoding='utf-8').splitlines():
    if line.startswith('U+'):
        code, readings = line.split(':', 1)
        characters[int(code[2:], 16)] = plain(readings.split('#')[0].strip().split(',')[0])

syllables = sorted(set(characters.values()))
assert all(s.isascii() and s.isalpha() and len(s) <= 6 for s in syllables)
indexes = {s: i for i, s in enumerate(syllables)}
phrases = {}
for line in (ROOT / 'third_party/phrase-pinyin-data/pinyin.txt').read_text(encoding='utf-8').splitlines():
    if line.startswith('#') or ':' not in line:
        continue
    text, reading = line.split(':', 1)
    words = plain(reading.split('#')[0].strip()).split()
    assert len(words) == len(text)
    assert all(w.isascii() and w.isalpha() and len(w) <= 6 for w in words)
    if ''.join(words) != ''.join(characters.get(ord(c), c) for c in text):
        phrases[text] = words

out = [
    '/* Generated by scripts/build-pinyin.py. Do not edit manually.',
    ' * Data: mozillazg/pinyin-data and mozillazg/phrase-pinyin-data (MIT).',
    ' * Sources, pinned revisions and licenses are in third_party/. */',
    '#ifndef SC_PINYIN_DATA_H', '#define SC_PINYIN_DATA_H',
    'static const char sc_pinyinSyllables[][7]={',
    ','.join('"%s"' % s for s in syllables), '};',
    'static const struct { unsigned int code; unsigned short syllable; } sc_pinyinCharacters[]={',
]
items = ['{0x%x,%d}' % (code, indexes[reading]) for code, reading in sorted(characters.items())]
out += [','.join(items[i:i+8]) + ',' for i in range(0, len(items), 8)]
out += ['};', 'static const struct { const wchar_t *text; const char *full,*initials; } sc_pinyinPhrases[]={']
for text in sorted(phrases, key=lambda s: s.encode('utf-16-be')):
    words = phrases[text]
    out.append('{%s,"%s","%s"},' % (wide(text), ''.join(words), ''.join(w[0] for w in words)))
out += ['};', '#define SC_PINYIN_PHRASE_MAX %d' % max(len(s.encode('utf-16-le')) // 2 for s in phrases), '#endif', '']
(ROOT / 'src/pinyin_data.h').write_text('\n'.join(out), encoding='utf-8')
print('Generated %d characters and %d phrase exceptions.' % (len(characters), len(phrases)))
